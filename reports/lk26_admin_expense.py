@dataclass
class CostRow:
    """管理费用明细表里"一行费用项目"的配置。

    【字段说明】
        key            内部标识（日志与调试用）
        label          财务名称（写日志用，与模板 A 列一致）
        row_no         模板行次（B 列的值，1~35）
        codes          参与汇总的科目编码（**加项**，精确匹配）
        exclude_codes  减项科目编码（默认空；如某项目需冲减某科目时用）
        pending        是否"需求已确认暂不处理"（口径不明，先不做）
        note           口径来源与备注（写日志便于与财务对账）

    【为什么科目要用元组（可空），而不是单字符串？】
        · 一个项目可能由多个明细科目构成（如"社保及公积金"通常拆成
          多个科目）；
        · 在科目清单到位前，允许为空 —— 空元组表示"待配置"，
          fetch/write 会自动跳过，不会报错也不会写错数。

    【exclude_codes 什么时候用？】
        当模板某项目是"净额"口径时（例如"其他"需扣除某个内部结转科目）。
        取数模型即：最终值 = sum(codes) - sum(exclude_codes)。

    【为什么用 row_no 而不是直接写 excel_row？】
        行次是模板的业务编号（B 列写着 1~35），不随程序改动而变，
        与财务对表时可直接引用"第 12 行 折旧费"。
        Excel 行号由 _row_of() 统一换算，换算规则只写一处。
    """

    key: str
    label: str
    row_no: int
    codes: tuple[str, ...] = ()
    exclude_codes: tuple[str, ...] = ()
    pending: bool = False
    note: str = ""

    @property
    def excel_row(self) -> int:
        """该行在 Excel 中的行号（1-based）。"""
        return _row_of(self.row_no)

    @property
    def status(self) -> str:
        """本行当前状态：已配置 / 暂不处理 / 待配置。

        【为什么需要这个属性？】
            本表的"没做"有两种，看起来一样、含义完全不同：

              ① **暂不处理**（pending=True）
                 财务明确说"这一行不明，先不做"。属于**有意的留空**。

              ② **待配置**（codes 为空、pending=False）
                 需求还没给到这一行，属于**待办**。

            两者在报表上都表现为"该行为空"。若不区分：
              · 看代码的人会把 ① 当成"漏做"，反复去追这条需求；
              · 或者把 ② 当成"已确认不做"，从此不再补 —— 报表静默缺项。

            这与 LK01/LK25 的 PENDING_ROWS 是同一套约定。
        """
        if self.codes:
            return "已配置"
        if self.pending:
            return "暂不处理"
        return "待配置"


