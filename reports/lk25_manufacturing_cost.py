def _period_text(ctx: ReportContext) -> str:
    """把 ctx.period 拼成模板要求的年月文案，如 "2026年5月"。

    【为什么要单独抽成函数，而不是在 write 里直接拼字符串？】
        需求第 1 条要求"C4 填界面所选的会计期间"。这个文案在本模块里
        既用于写值、也用于日志，若各处各拼一遍，日后要改格式
        （比如客户要求 "2026年05月"）就会漏改某一处，
        出现"日志显示 5 月、格子里却是 05 月"这种诡异不一致。

        集中一处后，格式只有一种定义。

    【★ 为什么绝不能写成常量？★】
        年月随时间变化。若写成 "2026年5月"，那么无论界面选哪个月，
        报表 C4 都显示 5 月 —— 而金额却是所选月份的数。
        看表的人会以为拿到的是 5 月表，实际是 8 月的数，
        且报表上完全看不出异常。这是这类报表最隐蔽的错误之一。

    【月份不补零 —— 与 LK01/LK02 保持一致】
        模板与已完成的表都用 "2026年5月"，不是 "2026年05月"。
        统一格式，避免同一份报表里两种写法并存。
    """
    return f"{ctx.period.year}年{ctx.period.month}月"


def _row_of(row_no: int) -> int:
    """模板行次 → Excel 行号（1-based）。

    【为什么可以直接加 8？】
        已逐行核对模板：
            行次 1（工资）      → Excel 第 9 行
            行次 25（其他）     → Excel 第 33 行
            行次 26（合计）     → Excel 第 34 行
        数据区从第 9 行起连续排列，恰好 row_no + 8。

        【注意】这是"核对过的结论"，不是"推算"。若模板将来插入行
        （比如在表头与数据区之间加了一行），这里必须同步改成
        FIRST_DATA_ROW + row_no - 1，并重新核对。
    """
    return FIRST_DATA_ROW + row_no - 1


