def _make_cell_map() -> dict[str, str]:
    """按 ROW_SPECS 自动生成 cell_map（指标名 → 单元格）。

    【为什么自动生成，而不是手写 35×13 个格子？】
        每行要登记 12 个月 + 1 个累计 = 13 个格子，35 行共 455 个。
        手写时漏一个，该格就不进勾稽核对清单，
        日后"核对通过"可能是假象（漏检）—— 这种漏检没有任何症状。
        自动生成后，"配置里有这一行"就必然意味着"这 13 格都登记了"。

    【O 列要不要登记？】
        要。虽然程序不写 O 列（模板公式），但 Excel 算出结果后，
        核对模块读回的是公式值，正可用于验证"月列之和 = 累计列"。

    【合计行要不要登记？】
        登记 O44（本年累计合计）。C44~N44 因模板公式区间存疑
        （详见模块头部口径②），仍照常登记 —— 登记的是"格位"，
        值与公式是否算对由后续核对环节判断，不在本函数里区别对待。
    """
    mapping: dict[str, str] = {"会计期间": PERIOD_CELL}
    for spec in ROW_SPECS:
        for month, col in COL_OF_MONTH.items():
            mapping[f"{spec.key}_{month}月"] = f"{col}{spec.excel_row}"
        mapping[f"{spec.key}_本年累计"] = f"{COL_YEAR_TOTAL}{spec.excel_row}"
    mapping["合计_本年累计"] = f"{COL_YEAR_TOTAL}{TOTAL_ROW}"
    return mapping


