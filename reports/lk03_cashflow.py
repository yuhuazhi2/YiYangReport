def _make_cell_map() -> dict[str, str]:
    """按 ROW_SPECS 自动生成 cell_map（指标名 → 单元格）。

    【为什么自动生成，而不是手写？】
        手写时漏一个，该格就不进勾稽核对清单，日后"核对通过"可能是
        假象（漏检）—— 而这种漏检没有任何症状。自动生成后，
        "配置里有这一行"就必然意味着"该登记的格子都登记了"。

    【★ 只登记"确实会写数值"的格子 ★】
        规范明确要求：cell_map 只能登记确实写了数值的格子。
        某行若明确不填 C 或 D（fill_current / fill_prev 为 False），
        登记进去只会让 verify() 读回 None，核对报告里该指标的
        结论永远是"无法核对"，真正的核对失败反而被淹没。

    【为什么仍保留 "会计期间"？】
        B4 是需求明确要求写入的格子，不属于任何 ROW_SPECS 行，必须单独登记。
    """
    mapping: dict[str, str] = {"会计期间": PERIOD_CELL}
    for spec in ROW_SPECS:
        if spec.fill_current:
            mapping[f"{spec.key}_本期金额"] = f"{COL_CURRENT}{spec.excel_row}"
        if spec.fill_prev:
            mapping[f"{spec.key}_上期金额"] = f"{COL_PREV}{spec.excel_row}"

    # 【余额类行同样要登记】
    #   它们与 ROW_SPECS 走不同的取数线，但产物一样是"写进某格的数值"，
    #   所以必须一并进 cell_map —— 否则 C45/D45 不进勾稽核对清单，
    #   而"核对通过"会是假象（漏检），且没有任何症状。
    for bspec in BALANCE_SPECS:
        if bspec.fill_current:
            mapping[f"{bspec.key}_本期金额"] = f"{COL_CURRENT}{bspec.excel_row}"
        if bspec.fill_prev:
            mapping[f"{bspec.key}_上期金额"] = f"{COL_PREV}{bspec.excel_row}"
    return mapping


