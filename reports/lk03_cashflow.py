@dataclass
class CashFlowRow:
    """现金流量表里"一行指标"的配置。

    字段：
        key         内部标识（日志与调试用）
        label       财务名称（写日志用，建议与模板 A 列一致）
        cash_items  参与汇总的**现金流量项目编码**（gl_cashtable.cCashItem）
        excel_row   模板中的 Excel 行号（1-based，见 EXCEL_ROW）
        direction   方向："inflow"（收到现金）或 "outflow"（支付现金）
        exclude_items  减项项目编码（默认空）
        fill_current   是否填 C 列（本期金额），默认 True
        fill_prev      是否填 D 列（上期金额），默认 True
        note        口径来源与备注（写日志，便于与财务对账）

    【★ direction 是为什么加的？（需求第 6 条）★】
        前三条都是"收到现金"，净额 = md - mc（借方为增项）。
        但"支付现金"类行在凭证里金额记在贷方，净额必须是 mc - md，
        否则会得到负数。

        【若方向写错会怎样？】
            以"购买商品支付的现金"为例，正确值应为正数（本期付了 1000）。
            若误用 md-mc，会得到 -1000。
            而模板的『经营活动现金流出小计』是把行次 6~9 **相加**，
            负数会把小计冲销掉 —— 报表上每个格子都"有数字"，
            只有小计偏小，肉眼几乎无法发现。

        【为什么做成字段，而不是在 fetch 里 if 判断行号？】
            后续还有行次 7、8、9、19~22、30~32 等大量"支付"类行，
            它们口径一致、只是项目编码不同。
            做成字段后，这些行只需配置 direction="outflow"，
            取数逻辑零改动；而 if 判断行号会让逻辑与坐标耦合，
            模板一旦挪行就会静默失效。

    【为什么取的是"现金流量项目"而不是"会计科目"？】
        现金流量项目（cCashItem，如 '01'）是 U8 在凭证上打的业务标记，
        它与会计科目是多对多的关系：一笔"借 银行存款 / 贷 主营业务收入"
        可能被标记为 '01 销售商品收到的现金'，另一笔同样科目的收款
        却可能标记为 '04 收到其他与经营活动有关的现金'。
        所以只能按项目编码取数，不能按科目。

    【fill_prev 为什么默认 True？】
        需求 20261106 已确认本表 D 列（上期金额）的通用口径：
        取**上一期**（iYPeriod 减一的那个月）的同一项目、同样算法。
        既然口径是表级的、对每一行都成立，就让它默认生效，
        避免每加一行都要记得手工打开开关（漏开会让 D 列静默空白）。
        若将来某行确实不填 D，显式设 False 即可。

    【exclude_items 现在没用上，为什么留着？】
        留给"净额列示"的行（例如"处置固定资产……收回的现金净额"
        可能需要从某项目里扣减另一项目）。
        与 LK01 / LK02 的 exclude_codes 同一机制：事先留好，
        将来不必为此改动 fetch。
    """

    key: str
    label: str
    cash_items: tuple[str, ...]
    excel_row: int
    direction: str = "inflow"
    exclude_items: tuple[str, ...] = ()
    fill_current: bool = True
    fill_prev: bool = True
    note: str = ""


