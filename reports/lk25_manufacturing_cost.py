    # ------------------------------------------------------------------
    def fetch(self, ctx: ReportContext) -> None:
        """一次取回所有"已配置科目"的费用发生额，再按行配置分流。

        【为什么合并成一次查询？】
            25 行涉及的科目可能有几十个，若每行各查一次就是几十次
            数据库往返。合并成一次后：
              · 只需 1 次查询；
              · 所有行看到的是同一份快照，不会出现"两行数据来自
                不同时刻"的一致性问题。

        【为什么科目为空时不查库？】
            空科目清单会拼出 `ccode IN ()` 这种非法 SQL（或空结果）。
            更重要的是：此时查库毫无意义，只会白白往返一次，
            并在审计日志里留下一条查不出任何东西的记录。
            所以直接返回，并明确告知"科目待配置"。
        """
        year, month = ctx.period.year, ctx.period.month

        configured = [s for s in ROW_SPECS if s.codes]
        # 【待配置 ≠ 暂不处理】
        #   pending=True 的行是需求已明确"暂不做"，
        #   不该混进"待需求提供"的清单里 —— 否则维护者会一直去追
        #   一条早已确认不做的需求。
        self.unconfigured_keys = [
            s.key for s in ROW_SPECS if not s.codes and not s.pending
        ]

        if not configured:
            # 【这是当前阶段的正常状态，用 INFO 而非 WARNING】
            #   科目清单尚未提供，每次生成都会走到这里。
            #   若打成 WARNING，维护者会对这条警告脱敏，
            #   真正的问题反而被淹没（与 LK02 的 optional 行同一考虑）。
            logger.info(
                "[%s] 全部 %d 行的科目尚未配置，本次不取数、不填数，"
                "仅保留模板版式与页眉。",
                self.code, len(ROW_SPECS),
            )
            return

        # 汇总所有已配置行的科目（去重 + 排序，保证缓存键稳定）
        # 【为什么要带上 exclude_codes？】减项科目也必须查回来才能减。
        all_codes = tuple(sorted({
            c
            for spec in configured
            for c in (*spec.codes, *spec.exclude_codes)
        }))

        # 【缓存键】必须带上科目集合，否则将来加行项目时会撞键。
        #   同一科目在不同口径下结果完全不同，撞键会让后取的覆盖先取的，
        #   而且两次都不报错。
        key = ctx.make_key("GL_accvouch", "LK25制造费用", *all_codes)

        # 【方向 credit + 摘要「结转制造费用」—— 需求第 2 条】
        #   见模块头部口径④：本表取的是月末转出到生产成本的那一笔，
        #   不是平时费用发生的借方金额。
        sql, params = u8.gl_expense_amount_by_period(
            year, all_codes,
            end_month=month,
            amount_side=AMOUNT_SIDE,
            digest_keywords=DIGEST_KEYWORDS,
        )

        try:
            rows = ctx.fetch(key, sql, params, report_code=self.code)
        except Exception as exc:  # noqa: BLE001
            # 单表取数失败不中断整体流程（43 张表里坏 1 张不牵连其他）
            logger.warning("[%s] 取数失败：%s", self.code, exc)
            rows = []

        # ---- 初始化每行的累加器 ----
        values: dict[str, dict[int, float]] = {s.key: {} for s in configured}
        has: dict[str, set[int]] = {s.key: set() for s in configured}

        # 科目 → [(所属行, 符号)]
        #   符号 +1 = 加项（codes），-1 = 减项（exclude_codes）
        #   一个科目可能同时被多行使用，故用 list。
        code_to_rows: dict[str, list[tuple[CostRow, int]]] = {}
        for spec in configured:
            for c in spec.codes:
                code_to_rows.setdefault(c, []).append((spec, +1))
            for c in spec.exclude_codes:
                code_to_rows.setdefault(c, []).append((spec, -1))

        # ---- 逐条分流累加 ----
        #
        # 超出所选期间的记录会被跳过（见下方"额外防线"），
        # 这里先攒起来，循环结束后**汇总成一条日志**。
        #
        # 【为什么汇总而不是逐条 WARNING？】
        #   正常情况 SQL 已用 end_month 截断，这些记录本不该出现。
        #   一旦出现，往往是一整批（如 6 月以后每个月都有），
        #   逐条打就是 9 条几乎相同的警告 —— 会把真正需要关注的
        #   日志淹没。汇总成一条，既保留了"确实发生过"的事实，
        #   又不喧宾夺主。
        out_of_range: list[str] = []

        for row in rows:
            try:
                # 列顺序由 gl_expense_amount_by_period 的 SELECT 决定：
                #   第0列 ccode、第1列 iperiod、第2列 amount
                ccode = str(row[0]).strip()
                iperiod = int(row[1])
                amount = float(row[2]) if row[2] is not None else 0.0
            except (IndexError, TypeError, ValueError) as exc:
                logger.warning("[%s] 跳过异常记录 %r：%s", self.code, row, exc)
                continue

            if not 1 <= iperiod <= 12:
                # U8 支持 13 期（调整期）等情形。明确跳过并记日志，
                # 不静默丢弃 —— 否则"某月没数"永远查不出原因。
                logger.warning("[%s] 跳过非法会计期间 iperiod=%s（科目 %s）",
                               self.code, iperiod, ccode)
                continue

            # 【额外防线：月份不得超过所选月份】
            #   SQL 里已用 end_month 限制，这里再判一次属于纵深防御：
            #   万一将来有人改了取数函数的区间，也不会让 6~12 月的数
            #   悄悄混进"5 月报表"。
            if iperiod > month:
                # 只记录、不逐条告警，循环后统一输出（见 out_of_range 说明）
                out_of_range.append(f"{ccode}-{iperiod}月")
                continue

            for spec, sign in code_to_rows.get(ccode, []):
                bucket = values[spec.key]
                bucket[iperiod] = bucket.get(iperiod, 0.0) + sign * amount

                # 【has 只由加项设置】
                #   若某行只有减项科目有记录、加项没有（数据异常），
                #   累加结果会是负数。此时不标记"有数据"，该格不写 ——
                #   宁可不写，也不写一个负数误导人。
                if sign > 0:
                    has[spec.key].add(iperiod)

        # ---- 超期记录汇总告警（正常情况下不应出现）----
        if out_of_range:
            logger.warning(
                "[%s] 跳过 %d 条超出所选期间（%d月）的记录：%s。"
                "取数 SQL 本应已用 end_month 截断，出现该提示请检查取数函数。",
                self.code, len(out_of_range), month,
                "、".join(out_of_range[:10])
                + ("…" if len(out_of_range) > 10 else ""),
            )

        # ---- 收口保存 + 逐行日志 ----
        for spec in configured:
            vals = values[spec.key]
            ok = has[spec.key]
            self.row_values[spec.key] = vals
            self.row_has[spec.key] = ok

            if not ok:
                # 【为什么用 INFO 而不是 WARNING？】
                #   费用项目"某月/整年没有发生额"是常态（例如本期未发生
                #   商业保险费）。若打成 WARNING，25 行里可能十几行报警，
                #   维护者很快就会对警告脱敏，真正的问题反而看不到。
                logger.info(
                    "[%s] %s（第%d行）：未取到 %d 月前的发生额，本行留空。",
                    self.code, spec.label, spec.excel_row, month)
                continue

            detail = "、".join(f"{m}月={vals[m]:.2f}" for m in sorted(ok))
            logger.info("[%s] %s（第%d行）：%s",
                        self.code, spec.label, spec.excel_row, detail)

    # ------------------------------------------------------------------
    # 第2步：填表
    # ------------------------------------------------------------------
    def write(self, hook: _SheetHook, ctx: ReportContext) -> None:
        """填页眉 + 会计期间 + 各月明细列。

        【★ 不写 O 列与第 34 行合计 ★】
            模板这两处都是 =SUM(...) 公式，由 Excel 自己算。
            写值会覆盖公式，详见模块头部口径①。
        """
        # 1) 通用页眉（公司名称等）
        # 【为什么 fill_period=False？】
        #   通用页眉会把年月写回"会计期间："标签所在格（A4）。
        #   而本表要求写到 C4。若两处都写，同一页会出现两个年月，
        #   财务会以为是数据重复。
        fill_common_header(hook, ctx, fill_period=False)

        # 2) 会计期间 → C4（需求第 1 条）
        #
        # 【取值来源是 ctx.period（界面所选年月），不是常量】
        #   界面选 2026年5月 → 写 "2026年5月"；选 2026年8月 → 写 "2026年8月"。
        #   详见 _period_text() 的说明。
        #
        # 【必须用 set_text，不能用 set】详见 PERIOD_CELL 的注释：
        #   C4 是金额格式格，用 set() 写年月会被 Excel 当成日期，
        #   存成序列号 46143，再显示成 "46,143.00"。
        #
        # 【这一句在"有没有取到数"之外】
        #   年月是报表的身份信息，与数据无关。哪怕本次一行数都没取到
        #   （科目未配置、数据库连不上），C4 也必须写上 ——
        #   否则打开文件根本分不清这是哪个月的报表。
        period_text = _period_text(ctx)
        hook.set_text(PERIOD_CELL, period_text)
        logger.info("[%s] 已写入 %s=%s（界面所选会计期间）",
                    self.code, PERIOD_CELL, period_text)

        # 3) 未取数的行：分两类记录，避免把"暂不处理"当成"待配置"
        #
        # 【为什么要分开说？】
        #   两者在报表上都表现为空白，但含义完全不同：
        #     · 暂不处理 → 已与财务确认，不必再追；
        #     · 待配置   → 需求还没给到，属待办事项。
        #   混在一起会让维护者分不清"哪几行还要继续跟"。
        pending_keys = [s.key for s in ROW_SPECS if s.pending and not s.codes]
        if pending_keys:
            logger.info(
                "[%s] 以下 %d 行需求确认「暂不处理」（口径不明），"
                "保持模板空白：%s",
                self.code, len(pending_keys), "、".join(pending_keys),
            )

        if self.unconfigured_keys:
            logger.info(
                "[%s] 以下 %d 行科目尚未配置（待需求提供），保持模板空白：%s",
                self.code, len(self.unconfigured_keys),
                "、".join(self.unconfigured_keys),
            )

        # 4) 逐行写月列
        for spec in ROW_SPECS:
            if not spec.codes:
                # 待配置行：不写（保持模板空白），也不重复打日志
                continue

            vals = self.row_values.get(spec.key, {})
            ok = self.row_has.get(spec.key, set())

            if not ok:
                # 【为什么不写 0？】
                #   数据库连不上、或该行本月没有发生额时，累加值是 0。
                #   若照写不误，报表会显示"本月折旧费为 0"，
                #   客户可能误认为"本月确实没折旧" —— 而这个结论
                #   与"未取到数据"是两回事。
                #   约定：**没取到数据就保持空白**，让空白本身成为
                #   "未取数"的信号；原因已在 fetch() 写入日志。
                logger.info("[%s] %s 无数据，整行保持空白（不写 0）",
                            self.code, spec.label)
                continue

            for month, col in COL_OF_MONTH.items():
                if month in ok:
                    hook.set(f"{col}{spec.excel_row}", vals[month])
                # 无数据的月份不写，保持模板原样（空白）

            logger.info(
                "[%s] 已写入 %s 行：%s",
                self.code, spec.label,
                "、".join(f"{COL_OF_MONTH[m]}{spec.excel_row}={vals[m]:.2f}"
                          for m in sorted(ok)),
            )

        # 5) O 列 / 合计行：默认交给模板公式
        #
        # 【为什么写在这里而不是每行里？】
        #   它们都是"整表级"的动作（合计行要跨所有行累加），
        #   集中一处便于将来切换 WRITE_YEAR_TOTAL / WRITE_TOTAL_ROW 时
        #   一眼看清哪些行为会因此改变。
        if WRITE_YEAR_TOTAL or WRITE_TOTAL_ROW:
            self._write_formula_fallbacks(hook)

    def _write_formula_fallbacks(self, hook: _SheetHook) -> None:
        """模板公式缺失时，由程序兜底写累计值/合计值。

        【默认不会被调用】只有 WRITE_YEAR_TOTAL / WRITE_TOTAL_ROW
        被显式改成 True 时才走到这里。

        【为什么做成"可选兜底"而不是默认行为？】
            模板 O 列与第 34 行确实带 =SUM(...) 公式（已用 COM 核实）。
            正常情况交给 Excel 算最省事，也不存在"公式被值覆盖"的风险。
            但对于"客户改过模板、公式被删掉"的情形，需要有一个开关
            能顶上 —— 否则报表累计列会一片空白，而程序毫无察觉。

        【为什么用 set 写值，而不是 set_formula？】
            · 写值：不依赖模板区域是否含合并单元格、不受插删行影响；
            · 写公式：需要精确知道区域范围，模板一改就可能算错。
            与 LK02 "本月累计用值累加、不写死 SUM 公式"的口径一致。
        """
        # 每列合计（仅对已配置且有数据的行累加）
        col_totals: dict[int, float] = {}
        for spec in ROW_SPECS:
            if not spec.codes:
                continue
            vals = self.row_values.get(spec.key, {})
            ok = self.row_has.get(spec.key, set())
            if not ok:
                continue

            if WRITE_YEAR_TOTAL:
                total = sum(vals[m] for m in ok)
                hook.set(f"{COL_YEAR_TOTAL}{spec.excel_row}", total)

            for m in ok:
                col_totals[m] = col_totals.get(m, 0.0) + vals[m]

        if WRITE_TOTAL_ROW and col_totals:
            for month, col in COL_OF_MONTH.items():
                if month in col_totals:
                    hook.set(f"{col}{TOTAL_ROW}", col_totals[month])
            hook.set(f"{COL_YEAR_TOTAL}{TOTAL_ROW}",
                     sum(col_totals.values()))